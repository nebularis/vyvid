"""Skills that reach an agent: a domain's or a project's own, composed for a project and written into it.

A domain ships ``skills/<name>/SKILL.md``. A project adds to one with ``<additions>/<domain>/<name>.md``, whose text joins
the skill under the heading of the same name, or takes that heading's place where the heading ends ``(replace)``, and whose
new headings follow at the end. ``{{name}}`` in a skill is a value of the project's ``skill_values``, else of the domain's.

The composed file names no folder of this machine, since it is committed and read on others. A skill names its registers
by family and domain, and an agent reaches them through the index.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .config import Config, Scope

MARK = "<!-- Generated by vyvid install. Do not edit, change the domain or the project's additions instead. -->"
# Ordered so that a client's own rule on names, lower case and dashes, holds for every project prefix.
NAME_RE = re.compile(r"[a-z][a-z0-9-]*\Z")
FRONT_RE = re.compile(r"\A---\n(.*?)\n---\n?", re.S)
HEADING_RE = re.compile(r"^## +(.+?)\s*$", re.M)
REPLACE_RE = re.compile(r"\s*\(replace\)$")
VALUE_RE = re.compile(r"(?<!\$)\{\{\s*([a-z][a-z0-9_.-]*)\s*\}\}")  # never a workflow's ${{ x }}
SPDX_RE = re.compile(r"<!-- SPDX-License-Identifier: [^>]*-->\s*")
FENCE_RE = re.compile(r"^(```|~~~)", re.M)
DEFAULT_VALUES = {"ask": "vyd find", "read": "vyd read", "misses": "vyd misses --near", "gap": "vyd gap"}

INDEX_FIRST = (
    "Before making any decision, ALWAYS check if the index can answer first. Before searching with any tool (e.g., PowerShell, "
    "grep, sed, awk, etc), ALWAYS see if the index can answer first. Anything the index misses gets recorded as a miss and "
    "presented back to the user as a potential index improvement."
)


def generated(text: str) -> bool:
    """Whether a file was written by this module. The marker follows the front matter."""
    return MARK in text.splitlines()[:12]


@dataclass(frozen=True)
class Written:
    """One composed skill: where it goes under a target, and its text, or why it could not be made."""

    name: str
    text: str
    problems: tuple[str, ...] = ()


def found(scope: Scope) -> dict[str, Path]:
    """The skills a scope ships, by name, from each folder its ``skills`` names. Anything else in the folder is not a skill."""
    out: dict[str, Path] = {}
    for folder in scope.readable(scope.skills):
        if folder.is_dir():
            out.update({p.parent.name: p for p in sorted(folder.glob("*/SKILL.md")) if p.is_file() and scope.readable([p])})
    return out


def front_matter(text: str) -> tuple[dict[str, str], str]:
    """The simple ``key: value`` lines of a skill's front matter, and the text after it."""
    match = FRONT_RE.match(text)
    if not match:
        return {}, text
    keys = {k.strip(): v.strip() for k, _, v in (line.partition(":") for line in match.group(1).splitlines()) if k.strip() and not k.startswith(" ")}
    return keys, text[match.end():]


def sections(text: str) -> tuple[str, list[tuple[str, str]]]:
    """The text before the first ``##`` heading, and each heading with its text. A heading inside a code fence is text."""
    fenced, positions, offset = False, [], 0
    for line in text.splitlines(keepends=True):
        if FENCE_RE.match(line):
            fenced = not fenced
        elif not fenced and HEADING_RE.match(line.rstrip("\n")):
            positions.append(offset)
        offset += len(line)
    if not positions:
        return text, []
    parts = []
    for n, start in enumerate(positions):
        end = positions[n + 1] if n + 1 < len(positions) else len(text)
        heading, _, body = text[start:end].partition("\n")
        parts.append((HEADING_RE.match(heading).group(1), body))
    return text[:positions[0]], parts


def merge(base: str, addition: str) -> str:
    """``base`` with ``addition`` joined by heading, as the module's opening says."""
    head, rows = sections(base)
    extra_head, extras = sections(addition)
    merged = {name: body for name, body in rows}
    order = [name for name, _ in rows]
    for raw, body in extras:
        name = REPLACE_RE.sub("", raw)
        if name not in merged:
            order.append(name)
            merged[name] = body.strip("\n") + "\n"
        elif raw != name:
            merged[name] = body.strip("\n") + "\n"
        else:
            merged[name] = merged[name].rstrip("\n") + "\n\n" + body.strip("\n") + "\n"
    if extra_head.strip():
        head = head.rstrip("\n") + "\n\n" + extra_head.strip("\n") + "\n\n"
    return head + "\n".join(f"## {name}\n{merged[name].rstrip()}\n" for name in order)


def registers_named(scope: Scope, project: Scope | None) -> list[str]:
    """A line for each register a reader of this skill can ask for, machine-independent."""
    lines = [f"- `{f.name}` entries of {scope.kind} {scope.name}, {f.type or 'entries'}" for f in scope.families.values() if f.type != "slice"]
    if project is not None and project is not scope:
        lines += [f"- `{f.name}` entries of project {project.name}, {f.type or 'entries'}" for f in project.families.values() if f.type != "slice"]
    return lines


def header(values: dict[str, str], lines: list[str]) -> str:
    """The block every generated skill opens on, written once here."""
    where = "\n".join(lines) or "- the registers of the scopes `vyd context` lists in this folder"
    return (f"## Ask the index first\n\n**{INDEX_FIRST}**\n\n"
            f"Ask with `{values['ask']} <the problem in your own words>`, then read an entry with `{values['read']} <ID>`. "
            f"Report what it answered weakly with `{values['misses']}`, and record a gap with `{values['gap']}`.\n\n"
            f"The index answers from these, among others:\n\n{where}\n")


def work_values(project: Scope | None) -> dict[str, str]:
    """The locations a project's ``work`` table gives, relative to its checkout, so they are stated once."""
    work = project.work if project is not None else None
    if work is None or project.code is None:
        return {}
    out = {}
    for key in ("status", "plans", "sketches", "validation", "decisions", "index", "roadmap"):
        path = getattr(work, key, None)
        if path is not None:
            try:
                out[key] = path.relative_to(project.code).as_posix()
            except ValueError:  # a documents folder outside the code folder keeps its project-relative name out of the file
                out[key] = path.name
    return out


def compose(text: str, scope: Scope, project: Scope | None, additions: str, name: str) -> Written:
    """The skill ``text`` of ``scope``, with what ``project`` adds, its values filled and the header placed first."""
    values = {**DEFAULT_VALUES, **scope.skill_values, **work_values(project), **(project.skill_values if project is not None else {})}
    keys, body = front_matter(text)
    add_keys, add_body = front_matter(additions)
    description = add_keys.get("description", keys.get("description", ""))
    problems = [] if description else [f"skill {name} has no description, so no client would load it"]
    merged = merge(body, add_body) if add_body.strip() else body
    missing: set[str] = set()
    filled = VALUE_RE.sub(lambda m: values.get(m.group(1)) or missing.add(m.group(1)) or m.group(0), merged)
    problems += [f"skill {name} needs a value for {k}, which neither the project's skill_values nor the domain's give" for k in sorted(missing)]
    plain = filled.lstrip("\n")
    notice = SPDX_RE.match(plain)
    plain = plain[notice.end():].lstrip("\n") if notice else plain
    title, _, rest = plain.partition("\n") if plain.startswith("# ") else (f"# {name}", "", plain)
    licence = f"{notice.group(0).strip()}\n" if notice else ""
    composed = (f"---\nname: {name}\ndescription: {description}\n---\n{MARK}\n{licence}\n{title}\n\n{header(values, registers_named(scope, project))}\n{rest.lstrip()}").rstrip() + "\n"
    return Written(name, composed, tuple(problems))


def skill_name(scope: Scope, short: str, project: Scope | None) -> str:
    """The installed name: the project's prefix and the skill's, or the domain's name and the skill's, unless it starts with it."""
    prefix = project.skill_prefix if project is not None and project.skill_prefix is not None else ""
    if prefix:
        return prefix + short.removeprefix(f"{scope.name}-")
    if project is None and scope.skill_prefix is not None:
        return scope.skill_prefix + short
    if project is not None and scope is project:
        return short
    return short if short == scope.name or short.startswith(f"{scope.name}-") else f"{scope.name}-{short}"


def absent(config: Config, project: Scope) -> list[str]:
    """The domains this project names that are not here: never configured, or configured with no folder. Their skills cannot be
    composed, which must never read as there being none."""
    gone = [f"{name}, which is not configured here" for name in project.dropped]
    return gone + [f"{name}, whose folder {config.domains[name].path} is missing" for name in config.domain_order(project)
                   if config.domains[name].path is None or not config.domains[name].path.is_dir()]


def for_project(config: Config, project: Scope) -> tuple[list[Written], list[str]]:
    """Every skill composed for ``project``, from its trusted domains and itself, and what it leaves out and why."""
    out: dict[str, Written] = {}
    notes: list[str] = []
    additions = project.skill_additions
    used: set[Path] = set()
    for name in config.domain_order(project):
        domain = config.domains[name]
        if not domain.trusted:
            notes.append(f"no skill from domain {name}, whose trust is {domain.trust}, which gives knowledge alone")
            continue
        if domain.visibility == "private":
            # A composed skill is committed, so a private domain's text would travel with the repository. Its skills stay in the user's folder.
            notes.append(f"no skill from domain {name} in this checkout, since it is private. vyd install --client writes its skills to the user's folder")
            continue
        for short, path in found(domain).items():
            extra = additions / name / f"{short}.md" if additions is not None else None
            text = ""
            if extra is not None and extra.is_file():
                text = extra.read_text(encoding="utf-8")
                used.add(extra)
            installed = skill_name(domain, short, project)
            written = compose(path.read_text(encoding="utf-8"), domain, project, text, installed)
            if installed in out:
                notes.append(f"skill {installed} of domain {name} takes the place of one from a parent")
            out[installed] = written
    for short, path in found(project).items():
        installed = skill_name(project, short, project)
        if installed in out:
            notes.append(f"project skill {installed} takes the place of a domain's")
        out[installed] = compose(path.read_text(encoding="utf-8"), project, project, "", installed)
    if additions is not None and additions.is_dir():
        notes += [f"{p} adds to no skill of a trusted domain, so nothing reads it" for p in sorted(additions.glob("*/*.md")) if p not in used]
    return list(out.values()), notes


def _target_folders(project: Scope) -> list[Path]:
    return [project.code / t for t in project.skill_targets] if project.code is not None else []


def install_project(config: Config, project: Scope, dry_run: bool) -> int:
    """Write the project's composed skills into it. 1 if anything was left alone or could not be made."""
    if not project.trusted:
        print(f"vyd: project {project.name}'s vyvid.toml is not trusted, so no skill is written. A person runs vyd trust in a terminal")
        return 1
    if project.code is None:
        print(f"vyd: project {project.name} has no code folder to write skills into")
        return 1
    if gone := absent(config, project):
        print(f"vyd: no skill was written or removed, since the project uses {'; '.join(gone)}")
        return 1
    skills, notes = for_project(config, project)
    for note in notes:
        print(f"NOTE: {note}")
    failed = 0
    for skill in skills:
        for problem in skill.problems:
            print(f"vyd: {problem}")
            failed = 1
    keep = {s.name for s in skills}
    for folder in _target_folders(project):
        for skill in skills:
            if skill.problems:
                continue
            path = folder / skill.name / "SKILL.md"
            if path.exists() and not generated(path.read_text(encoding="utf-8", errors="replace")):
                print(f"left {path}, which exists and was not generated by vyvid install")
                failed = 1
                continue
            print(f"{'would write' if dry_run else 'wrote'} {path}")
            if not dry_run:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(skill.text, encoding="utf-8", newline="\n")
        for old in sorted(folder.glob("*/SKILL.md")) if folder.is_dir() else []:
            if old.parent.name not in keep and generated(old.read_text(encoding="utf-8", errors="replace")):
                print(f"{'would remove' if dry_run else 'removed'} {old}")
                if not dry_run:
                    old.unlink()
                    try:
                        old.parent.rmdir()
                    except OSError:
                        pass
    return failed


def normalised(line: str) -> str:
    """A line as the coverage check compares it, without its list or quote mark and its spacing."""
    return " ".join(re.sub(r"^\s*(?:[-*>]|\d+\.)\s+", "", line).split())


def coverage(source: Path, composed: list[Written], mapped: dict[int, str]) -> list[str]:
    """Each line of ``source`` that holds words and is neither in a composed skill nor given a home by ``mapped``, by line."""
    held = {normalised(line) for skill in composed for line in skill.text.splitlines()}
    lines = source.read_text(encoding="utf-8").splitlines()
    keys, _ = front_matter(source.read_text(encoding="utf-8"))
    skip = len(FRONT_RE.match(source.read_text(encoding="utf-8")).group(0).splitlines()) if keys else 0
    return [f"{source}:{n}: {line[:100]}" for n, line in enumerate(lines, 1)
            if n > skip and line.strip() and normalised(line) not in held and n not in mapped]


def read_map(path: Path) -> dict[int, str]:
    """A map of lines to their homes, tab-separated with a ``line`` and a ``destination`` column, rows with no destination left out."""
    rows = path.read_text(encoding="utf-8").splitlines()
    names = rows[0].split("\t") if rows else []
    if "line" not in names or "destination" not in names:
        raise ValueError(f"{path} has no line and destination columns")
    at, to = names.index("line"), names.index("destination")
    out = {}
    for row in rows[1:]:
        cells = row.split("\t")
        if len(cells) > max(at, to) and cells[at].strip().isdigit() and cells[to].strip():
            out[int(cells[at])] = cells[to].strip()
    return out


def check(config: Config, project: Scope, sources: list[Path], map_path: Path | None) -> int:
    """Fail where a committed skill differs from what its sources compose to, or a line of ``sources`` has no home."""
    if not project.trusted:
        print(f"vyd: project {project.name}'s vyvid.toml is not trusted, so its skills were not checked")
        return 2
    if project.code is None:
        print(f"vyd: project {project.name} has no code folder")
        return 2
    if gone := absent(config, project):
        print(f"skills check not run, since the project uses {'; '.join(gone)}")
        return 2
    skills, notes = for_project(config, project)
    for note in notes:
        print(f"NOTE: {note}")
    problems = [p for s in skills for p in s.problems]
    keep = {s.name for s in skills}
    for folder in _target_folders(project):
        for skill in skills:
            path = folder / skill.name / "SKILL.md"
            if not path.is_file():
                problems.append(f"{path} is missing. Run vyd install --project")
            elif not skill.problems and path.read_text(encoding="utf-8") != skill.text:
                problems.append(f"{path} differs from what its sources compose to. Run vyd install --project")
        for old in sorted(folder.glob("*/SKILL.md")) if folder.is_dir() else []:
            if old.parent.name not in keep and generated(old.read_text(encoding="utf-8", errors="replace")):
                problems.append(f"{old} was generated and no source makes it now. Run vyd install --project")
    mapped = read_map(map_path) if map_path else {}
    for source in sources:
        problems += coverage(source, skills, mapped if len(sources) == 1 else {})
    for problem in problems:
        print(f"ERROR: {problem}")
    print(f"skills check {'failed' if problems else 'passed'}: {len(skills)} composed, {len(problems)} problem(s)")
    return 1 if problems else 0
