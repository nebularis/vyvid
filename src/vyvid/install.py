"""``vyd install``: the files a client reads so that its agents meet Вивід.

For a client it writes one user-level rule file, which tells an agent to run ``vyd context`` before
its first task in a folder, and one skill per configured domain, naming the domain's rules, recipes
and registers. Every file carries a marker comment, and a file without the marker is never
overwritten, since it is somebody's own. Nothing is written into a project's folder.
"""

from __future__ import annotations

import json
from pathlib import Path

from .config import Config, Scope

# The folder each supported client reads rules and skills from.
CLIENTS = {"claude-code": "~/.claude"}
MARK = "<!-- Generated by vyvid install. Do not edit, change the domain instead. -->"

RULE = """\
# Вивід

Before the first task in a folder, run `vyd context` there and read each layer it lists, in order. The project's layer is last and overrides the ones before it.

Ask `vyd find` before a design, modelling, code or efficiency decision, since the index is more current than memory.

Where the context lists a recipe for the work, run it with `vyd recipe run <name> "<question>"`.

At a handoff, report the questions the index answered weakly with `vyd misses --near`.
"""


def generated(text: str) -> bool:
    """Whether a file was written by this command. A skill's marker follows its front matter, so any
    of the first lines may hold it."""
    return MARK in text.splitlines()[:6]


def skill(domain: Scope) -> str:
    """The skill generated from a domain: its rules, then its recipes, then where its registers are."""
    description = domain.description or f"Use when working on {domain.name}"
    parts = [f"---\nname: vyvid-{domain.name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n---\n{MARK}\n\n# {domain.name}"]
    parts += [text for rules in domain.rules if rules.is_file() and (text := rules.read_text(encoding="utf-8").strip())]
    if domain.recipes:
        lines = [f'- `vyd recipe run {r.name} "<question>"`. {r.description}' for r in domain.recipes]
        parts.append("## Recipes\n\nRun one from the folder of the work.\n\n" + "\n".join(lines))
    registers = [f"- {f.name} ({f.type or 'entries'}) in {place}" for f in domain.families.values()
                 for place in [f.defined, *f.also] if place is not None]
    if registers:
        parts.append("## Registers\n\n" + "\n".join(registers))
    return "\n\n".join(parts) + "\n"


def files(config: Config, root: Path) -> list[tuple[Path, str]]:
    """Every file to write under ``root``, with its text."""
    return [(root / "rules" / "vyvid.md", f"{MARK}\n\n{RULE}"),
            *((root / "skills" / f"vyvid-{d.name}" / "SKILL.md", skill(d)) for d in config.domains.values())]


def install(config: Config, client: str, target: Path | None, dry_run: bool) -> int:
    """Write the client's files, or say what would be written. Returns 1 if a file was left alone,
    and 2 if the target lies inside a project."""
    root = (target or Path(CLIENTS[client])).expanduser()
    for project in config.projects.values():
        for folder in (project.code, project.docs):
            if folder and (root.resolve() == folder.resolve() or folder.resolve() in root.resolve().parents):
                print(f"vyd: {root} is inside the folder of project {project.name}, and install writes nothing there")
                return 2
    left = 0
    for path, text in files(config, root):
        if path.exists() and not generated(path.read_text(encoding="utf-8", errors="replace")):
            print(f"left {path}, which exists and was not generated by vyvid install")
            left += 1
            continue
        print(f"{'would write' if dry_run else 'wrote'} {path}")
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return 1 if left else 0
